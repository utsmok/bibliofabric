#!/usr/bin/env python
"""Generate the committed sync twins from the async sources.

Rewrites every ``packages/<pkg>/src/**/_async/*.py`` (except
``_concurrency.py``, which has hand-written twins) into a sibling ``_sync/``
module, and ``packages/<pkg>/tests/_async/`` into ``packages/<pkg>/tests/_sync/``.
Generated files get a header comment and are formatted with ruff.

Classes defined in an ``_async`` module are renamed: ``X`` becomes ``SyncX``,
except entry points following ``<Name>Client`` -> ``<Name>SyncClient``. The
renames are collected across the whole package (sources and tests) so every
generated file sees the same class names.

Per-package extra token replacements live in that package's ``pyproject.toml``::

    [tool.unasync]
    replacements = { "acquire_page" = "acquire_page_sync" }

Run ``uv run python scripts/unasync.py`` after changing any ``_async`` module;
CI and pre-commit run ``--check`` to fail on stale output.
"""

from __future__ import annotations

import argparse
import ast
import shutil
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

# This file is itself called unasync.py; drop its directory from sys.path so
# `import unasync` resolves to the installed package, not to this script.
sys.path[:] = [
    entry
    for entry in sys.path
    if Path(entry or ".").resolve() != Path(__file__).parent.resolve()
]

import unasync  # noqa: E402  (must come after the sys.path fix above)

HEADER = "# Generated by scripts/unasync.py; do not edit.\n"

# unasync's own defaults already cover the async/await keywords, the async
# dunder methods, AsyncIterator/AsyncIterable/AsyncGenerator, and
# StopAsyncIteration.
STANDARD_REPLACEMENTS = {
    "aclose": "close",
    "aread": "read",
    "aiter_bytes": "iter_bytes",
    "aiter_text": "iter_text",
    "aiter_lines": "iter_lines",
    "async_authenticate": "authenticate",
    "async_close": "close",
    "AsyncClient": "Client",
    "AsyncRetrying": "Retrying",
    "aiter": "iter",
    "anext": "next",
    "_async": "_sync",
}

GENERATED_SUFFIX = "_sync"


def package_dirs(selected: list[str] | None = None) -> list[Path]:
    """Return the workspace member directories, in stable order."""
    available = {
        p.name: p.resolve() for p in Path("packages").iterdir() if (p / "src").is_dir()
    }
    if not selected:
        return [available[name] for name in sorted(available)]
    unknown = [name for name in selected if name not in available]
    if unknown:
        valid = ", ".join(sorted(available))
        raise SystemExit(
            f"Unknown package(s): {', '.join(unknown)}. Available: {valid}."
        )
    return [available[name] for name in dict.fromkeys(selected)]


def collect_existing_sync(package: Path) -> set[Path]:
    """List generated ``_sync`` files currently on disk, excluding hand-written twins."""
    cwd = Path.cwd()
    existing = [
        path
        for path in (package / "src").rglob("*.py")
        if GENERATED_SUFFIX in path.parts and path.name != "_concurrency.py"
    ]
    tests_sync = package / "tests" / GENERATED_SUFFIX
    if tests_sync.is_dir():
        existing.extend(tests_sync.rglob("*.py"))
    return {path.resolve().relative_to(cwd) for path in existing}


def extra_replacements(package: Path) -> dict[str, str]:
    """Read ``[tool.unasync] replacements`` from the package's pyproject.toml."""
    pyproject = package / "pyproject.toml"
    if not pyproject.exists():
        return {}
    data = tomllib.loads(pyproject.read_text(encoding="utf-8"))
    table = data.get("tool", {}).get("unasync", {}).get("replacements", {})
    return {str(key): str(value) for key, value in table.items()}


def collect_sources(package: Path) -> list[Path]:
    """List every file that generates a sync twin, sorted for stable output."""
    files = [
        path
        for path in (package / "src").rglob("*.py")
        if "_async" in path.parts and path.name != "_concurrency.py"
    ]
    tests_async = package / "tests" / "_async"
    if tests_async.is_dir():
        files.extend(tests_async.rglob("*.py"))
    return sorted(set(files))


# Core framework classes keep the plain ``Sync`` prefix; the generic
# ``<Name>Client`` rule is for concrete client entry points.
CORE_CLASS_RENAMES = {
    "BaseApiClient": "SyncBaseApiClient",
    "ResourceClient": "SyncResourceClient",
}


def class_renames(files: list[Path]) -> dict[str, str]:
    """Map every top-level class defined in the package to its sync name."""
    names: set[str] = set()
    for path in files:
        tree = ast.parse(path.read_text(encoding="utf-8"))
        names.update(node.name for node in tree.body if isinstance(node, ast.ClassDef))
    renames: dict[str, str] = {}
    for name in sorted(names):
        if name.startswith("_"):
            continue  # private helpers keep their name in the twin
        if name in CORE_CLASS_RENAMES:
            renames[name] = CORE_CLASS_RENAMES[name]
        elif name.endswith("Client"):
            renames[name] = f"{name.removesuffix('Client')}SyncClient"
        else:
            renames[name] = f"Sync{name}"
    return renames


def render(files: list[Path], rule: unasync.Rule) -> dict[Path, str]:
    """Generate the sync files in a scratch tree and return path -> content.

    The output is headered and ruff-formatted, exactly what write mode puts
    on disk, so check mode compares like with like.
    """
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        rels = [path.relative_to(Path.cwd()) for path in files]
        for rel in rels:
            (root / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(rel, root / rel)
        unasync.unasync_files(
            [str(root / rel) for rel in rels],
            [rule],
        )
        formatted = [Path(str(rel).replace("_async", GENERATED_SUFFIX)) for rel in rels]
        # unasync can leave imports unsorted (AsyncIterator -> Iterator);
        # sort them before formatting so check and write agree.
        # The scratch tree has no pyproject.toml above it, so ruff would use
        # defaults; pin the repo config explicitly.
        config = str(Path.cwd() / "pyproject.toml")
        subprocess.run(
            [
                sys.executable,
                "-m",
                "ruff",
                "check",
                "--config",
                config,
                "--fix",
                "--select",
                "I",
                "-q",
                *formatted,
            ],
            cwd=root,
            check=True,
        )
        subprocess.run(
            [
                sys.executable,
                "-m",
                "ruff",
                "format",
                "--config",
                config,
                "-q",
                *formatted,
            ],
            cwd=root,
            check=True,
        )
        return {
            rel: HEADER + (root / rel).read_text(encoding="utf-8") for rel in formatted
        }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.partition("\n")[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero when a generated file is stale or orphaned, without writing",
    )
    parser.add_argument(
        "--package",
        action="append",
        dest="packages",
        help="workspace package name to process (repeatable; default: all packages)",
    )
    args = parser.parse_args()

    selected_packages = package_dirs(args.packages)
    stale: list[Path] = []
    orphans: list[Path] = []
    written = 0
    for package in selected_packages:
        files = collect_sources(package)
        if not files:
            if args.check:
                orphans.extend(sorted(collect_existing_sync(package)))
            continue
        replacements = {
            **STANDARD_REPLACEMENTS,
            **CORE_CLASS_RENAMES,  # client packages subclass the core classes
            **extra_replacements(package),
            **class_renames(files),
        }
        rule = unasync.Rule(
            fromdir="_async",
            todir=GENERATED_SUFFIX,
            additional_replacements=replacements,
        )
        rendered = render(files, rule)
        if args.check:
            existing = collect_existing_sync(package)
            orphans.extend(sorted(existing - set(rendered)))
        for rel, content in sorted(rendered.items()):
            target = Path(rel)
            if args.check:
                current = target.read_text(encoding="utf-8") if target.exists() else ""
                if current != content:
                    stale.append(target)
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content, encoding="utf-8")
                written += 1

    if stale or orphans:
        for path in stale:
            print(f"stale: {path}")
        for path in orphans:
            print(f"orphan: {path}")
        print(
            "Run `uv run python scripts/unasync.py` to regenerate the sync twins"
            " (and delete any orphan `_sync` files).",
            file=sys.stderr,
        )
        return 1
    verb = "checked" if args.check else "generated"
    print(f"{verb} {written or 'all'} sync files for {len(selected_packages)} packages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
