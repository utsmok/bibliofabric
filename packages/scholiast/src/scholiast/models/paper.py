"""Pydantic models for Semantic Scholar papers, citations, and references."""

from typing import Any

from bibliofabric import SafeList, SafeStr
from pydantic import BaseModel, ConfigDict

from .author import Author


class ExternalIds(BaseModel):
    """The paper's identifiers in external catalogs.

    ``CorpusId`` is the integer Semantic Scholar corpus id; the others use
    the catalog's own spelling (for example ``ArXiv`` and ``MAG`` carry
    strings). Fields the paper lacks are ``None``.
    """

    ACL: SafeStr | None = None
    ArXiv: SafeStr | None = None
    MAG: SafeStr | None = None
    PubMed: SafeStr | None = None
    PubMedCentral: SafeStr | None = None
    DBLP: SafeStr | None = None
    CorpusId: int | None = None
    DOI: SafeStr | None = None
    Medline: SafeStr | None = None

    model_config = ConfigDict(extra="allow")


class Journal(BaseModel):
    """The journal a paper appeared in, when the API knows one."""

    name: SafeStr | None = None
    volume: SafeStr | None = None
    pages: SafeStr | None = None

    model_config = ConfigDict(extra="allow")


class OpenAccessPdf(BaseModel):
    """The open-access PDF of a paper, with status and license from Unpaywall."""

    url: SafeStr | None = None
    status: SafeStr | None = None
    license: SafeStr | None = None
    disclaimer: SafeStr | None = None

    model_config = ConfigDict(extra="allow")


class Tldr(BaseModel):
    """One-sentence summary generated by the SciTLDR model."""

    model: SafeStr | None = None
    text: SafeStr | None = None

    model_config = ConfigDict(extra="allow")


class Embedding(BaseModel):
    """A SPECTER paper embedding (needs an API key with embeddings access)."""

    model: SafeStr | None = None
    vector: SafeList[float] = []

    model_config = ConfigDict(extra="allow")


class S2FieldOfStudy(BaseModel):
    """One field-of-study assignment of the S2FOS classifier or an external source."""

    category: SafeStr | None = None
    source: SafeStr | None = None

    model_config = ConfigDict(extra="allow")


class PublicationVenue(BaseModel):
    """The normalized journal or conference a paper appeared in."""

    id: SafeStr | None = None
    name: SafeStr | None = None
    type: SafeStr | None = None
    alternate_names: SafeList[str] = []
    url: SafeStr | None = None

    model_config = ConfigDict(extra="allow")


class Paper(BaseModel):
    """A Semantic Scholar paper record.

    The API returns ``paperId`` (plus ``title`` and ``year`` on some
    routes) even without ``fields``; every other field appears only when
    the caller asks for it in ``fields``. ``embedding`` and
    ``openAccessDoi`` need an API key; keyless requests that ask for them
    answer HTTP 400.
    """

    paperId: SafeStr | None = None
    corpusId: int | None = None
    externalIds: ExternalIds | None = None
    url: SafeStr | None = None
    title: SafeStr | None = None
    abstract: SafeStr | None = None
    venue: SafeStr | None = None
    publicationVenue: PublicationVenue | None = None
    year: int | None = None
    referenceCount: int | None = None
    citationCount: int | None = None
    influentialCitationCount: int | None = None
    isOpenAccess: bool | None = None
    openAccessPdf: OpenAccessPdf | None = None
    openAccessDoi: SafeStr | None = None
    fieldsOfStudy: SafeList[str] = []
    s2FieldsOfStudy: SafeList[S2FieldOfStudy] = []
    publicationTypes: SafeList[str] = []
    publicationDate: SafeStr | None = None
    journal: Journal | None = None
    authors: SafeList[Author] = []
    citationStyles: Any = None
    textAvailability: Any = None
    tldr: Tldr | None = None
    embedding: Embedding | None = None
    citations: SafeList[Any] = []
    references: SafeList[Any] = []
    matchScore: float | None = None

    model_config = ConfigDict(extra="allow")


class CitationContext(BaseModel):
    """One citation context paired with the intents it expresses."""

    contexts: SafeList[str] = []
    intents: SafeList[str] = []

    model_config = ConfigDict(extra="allow")


class Citation(BaseModel):
    """One edge of ``/paper/{id}/citations``: the citing paper plus contexts."""

    citingPaper: Paper | None = None
    contexts: SafeList[str] = []
    contextsWithIntent: SafeList[CitationContext] = []
    intents: SafeList[str] = []
    isInfluential: bool | None = None

    model_config = ConfigDict(extra="allow")


class Reference(BaseModel):
    """One edge of ``/paper/{id}/references``: the cited paper plus contexts."""

    citedPaper: Paper | None = None
    contexts: SafeList[str] = []
    contextsWithIntent: SafeList[CitationContext] = []
    intents: SafeList[str] = []
    isInfluential: bool | None = None

    model_config = ConfigDict(extra="allow")


class AutocompletePaper(BaseModel):
    """One candidate of ``/paper/autocomplete`` (minimal record)."""

    id: SafeStr | None = None
    title: SafeStr | None = None
    authorsYear: SafeStr | None = None

    model_config = ConfigDict(extra="allow")


class PaperMatch(BaseModel):
    """The single best title match of ``/paper/search/match``.

    The API returns ``matchScore`` next to the paper fields.
    """

    paper: Paper | None = None
    matchScore: float | None = None

    model_config = ConfigDict(extra="allow")

    @classmethod
    def from_record(cls, record: dict[str, Any]) -> "PaperMatch":
        """Build one match from the raw API record.

        The API nests nothing: the record is the paper itself with
        ``matchScore`` beside it.
        """
        fields = {key: value for key, value in record.items() if key != "matchScore"}
        return cls(
            paper=Paper.model_validate(fields),
            matchScore=record.get("matchScore"),
        )


